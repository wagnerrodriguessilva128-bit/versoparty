-- O bucket é público para que os vídeos aprovados possam ser reproduzidos.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('videos', 'videos', true, 52428800, array['video/mp4','video/webm','video/quicktime'])
on conflict (id) do update set public = true, file_size_limit = 52428800;

create table if not exists public.videos (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  author text not null check (char_length(author) between 1 and 40),
  title text not null check (char_length(title) between 1 and 90),
  description text default '',
  kind text not null check (kind in ('file','youtube')),
  youtube_url text,
  file_path text,
  status text not null default 'pending' check (status in ('pending','approved','rejected'))
);
create table if not exists public.likes (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  video_id bigint not null references public.videos(id) on delete cascade
);
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  video_id bigint not null references public.videos(id) on delete cascade,
  author text not null check (char_length(author) between 1 and 40),
  body text not null check (char_length(body) between 1 and 300)
);

alter table public.videos enable row level security;
alter table public.likes enable row level security;
alter table public.comments enable row level security;

drop policy if exists "Public can view approved videos" on public.videos;
create policy "Public can view approved videos" on public.videos for select to anon, authenticated using (status = 'approved');
drop policy if exists "Anyone can submit videos for review" on public.videos;
create policy "Anyone can submit videos for review" on public.videos for insert to anon, authenticated with check (status = 'pending');

drop policy if exists "Public can read likes" on public.likes;
create policy "Public can read likes" on public.likes for select to anon, authenticated using (true);
drop policy if exists "Anyone can like" on public.likes;
create policy "Anyone can like" on public.likes for insert to anon, authenticated with check (exists(select 1 from public.videos where videos.id = video_id and videos.status = 'approved'));

drop policy if exists "Public can read comments on approved videos" on public.comments;
create policy "Public can read comments on approved videos" on public.comments for select to anon, authenticated using (exists(select 1 from public.videos where videos.id = video_id and videos.status = 'approved'));
drop policy if exists "Anyone can comment on approved videos" on public.comments;
create policy "Anyone can comment on approved videos" on public.comments for insert to anon, authenticated with check (exists(select 1 from public.videos where videos.id = video_id and videos.status = 'approved'));

drop policy if exists "Public can watch uploaded videos" on storage.objects;
create policy "Public can watch uploaded videos" on storage.objects for select to anon, authenticated using (bucket_id = 'videos');
drop policy if exists "Anyone can upload a video file" on storage.objects;
create policy "Anyone can upload a video file" on storage.objects for insert to anon, authenticated with check (bucket_id = 'videos');
